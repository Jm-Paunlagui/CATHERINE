-- ============================================================================
--  04_platform_tables.sql
--  Additive migration — creates the platform tables added to 01_schema.sql
--  (sections 6-9) on an EXISTING install, WITHOUT dropping anything.
-- ============================================================================
--
--  TABLES
--  ------
--    T_AUTH_REFRESH_TOKEN_DEV            auth.refresh.token.model.js
--    T_SERVER_BACKUP_TOKEN_CONSUMED_DEV  backup-token.model.js
--    T_SERVER_BACKUP_DELETE_VOTE_DEV     backup-vote.model.js
--    T_SYSTEM_CONFIG_DEV                 system.config.model.js
--
--  WHEN YOU NEED THIS
--  ------------------
--  Your schema was created from an older 01_schema.sql and sign-in / refresh /
--  sign-out fails with:
--
--      ORA-00942: table or view does not exist
--
--  A fresh install does NOT need this file: 01_schema.sql creates every table
--  below with identical DDL. Running it anyway is harmless (see IDEMPOTENT).
--
--  IDEMPOTENT
--  ----------
--  Each table and index is created only when USER_TABLES / USER_INDEXES says it
--  is missing. Existing tables are never altered or dropped. If a table exists
--  with a different shape, fix it by hand — this script will not touch it.
--
--  HOW TO RUN
--  ----------
--    sqlplus  <user>/<password>@<host>:<port>/<service>  @04_platform_tables.sql
--  or open in SQL Developer and Run Script (F5).
-- ============================================================================

SET SERVEROUTPUT ON
SET DEFINE OFF

DECLARE
    -- Runs p_ddl only when table p_table is absent.
    PROCEDURE create_table_if_missing(p_table IN VARCHAR2, p_ddl IN VARCHAR2) IS
        c PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO c FROM USER_TABLES WHERE TABLE_NAME = p_table;
        IF c = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('created table ' || p_table);
        ELSE
            DBMS_OUTPUT.PUT_LINE('exists        ' || p_table);
        END IF;
    END;

    -- Runs p_ddl only when index p_index is absent.
    PROCEDURE create_index_if_missing(p_index IN VARCHAR2, p_ddl IN VARCHAR2) IS
        c PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO c FROM USER_INDEXES WHERE INDEX_NAME = p_index;
        IF c = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('created index ' || p_index);
        END IF;
    END;
BEGIN
    -- 6. Refresh-token ledger ------------------------------------------------
    create_table_if_missing('T_AUTH_REFRESH_TOKEN_DEV', q'[
        CREATE TABLE T_AUTH_REFRESH_TOKEN_DEV (
          ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
          JTI_HASH       VARCHAR2(64)   NOT NULL,
          FAMILY_ID      VARCHAR2(36)   NOT NULL,
          USER_ID        VARCHAR2(100)  NOT NULL,
          ROLE_SOURCE    VARCHAR2(8)    NOT NULL,
          ISSUED_AT      TIMESTAMP      NOT NULL,
          EXPIRES_AT     TIMESTAMP      NOT NULL,
          USED_AT        TIMESTAMP,
          REPLACED_BY    VARCHAR2(64),
          REVOKED_AT     TIMESTAMP,
          REVOKE_REASON  VARCHAR2(16),
          CONSTRAINT PK_T_AUTH_REFRESH_TOKEN_DEV PRIMARY KEY (ID),
          CONSTRAINT UQ_TART_JTI_HASH     UNIQUE (JTI_HASH),
          CONSTRAINT CHK_TART_HASH_LEN    CHECK (LENGTH(JTI_HASH) = 64),
          CONSTRAINT CHK_TART_ROLE_SOURCE CHECK (ROLE_SOURCE IN ('admin', 'user')),
          CONSTRAINT CHK_TART_EXPIRY      CHECK (EXPIRES_AT > ISSUED_AT),
          CONSTRAINT CHK_TART_USED_PAIR   CHECK (
               (USED_AT IS NULL     AND REPLACED_BY IS NULL)
            OR (USED_AT IS NOT NULL AND REPLACED_BY IS NOT NULL)),
          CONSTRAINT CHK_TART_REVOKE_PAIR CHECK (
               (REVOKED_AT IS NULL     AND REVOKE_REASON IS NULL)
            OR (REVOKED_AT IS NOT NULL AND REVOKE_REASON IN
                  ('LOGOUT', 'PASSWORD_CHANGE', 'PASSWORD_RESET', 'ADMIN_READD', 'REUSE')))
        )]');
    create_index_if_missing('IDX_TART_FAMILY',
        'CREATE INDEX IDX_TART_FAMILY ON T_AUTH_REFRESH_TOKEN_DEV (FAMILY_ID)');
    create_index_if_missing('IDX_TART_USER',
        'CREATE INDEX IDX_TART_USER ON T_AUTH_REFRESH_TOKEN_DEV (USER_ID)');
    create_index_if_missing('IDX_TART_EXPIRES',
        'CREATE INDEX IDX_TART_EXPIRES ON T_AUTH_REFRESH_TOKEN_DEV (EXPIRES_AT)');

    -- 7. Spent backup-token nonces ------------------------------------------
    create_table_if_missing('T_SERVER_BACKUP_TOKEN_CONSUMED_DEV', q'[
        CREATE TABLE T_SERVER_BACKUP_TOKEN_CONSUMED_DEV (
          JTI          VARCHAR2(64)  NOT NULL,
          EMP_ID       NUMBER        NOT NULL,
          EXPIRES_AT   TIMESTAMP     NOT NULL,
          CONSUMED_AT  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
          CONSTRAINT PK_SBTC_JTI PRIMARY KEY (JTI)
        )]');
    create_index_if_missing('IDX_SBTC_EXPIRES_AT',
        'CREATE INDEX IDX_SBTC_EXPIRES_AT ON T_SERVER_BACKUP_TOKEN_CONSUMED_DEV (EXPIRES_AT)');

    -- 8. Backup deletion votes ----------------------------------------------
    create_table_if_missing('T_SERVER_BACKUP_DELETE_VOTE_DEV', q'[
        CREATE TABLE T_SERVER_BACKUP_DELETE_VOTE_DEV (
          VOTE_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
          ARCHIVE_ID    VARCHAR2(200)  NOT NULL,
          REQUESTED_BY  NUMBER         NOT NULL,
          VOTED_BY      NUMBER         NOT NULL,
          VOTED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
          CONSTRAINT PK_T_SERVER_BACKUP_DELETE_VOTE_DEV PRIMARY KEY (VOTE_ID),
          CONSTRAINT UIX_SBDV_ARCHIVE_VOTER UNIQUE (ARCHIVE_ID, VOTED_BY)
        )]');

    -- 9. Signed key/value config --------------------------------------------
    create_table_if_missing('T_SYSTEM_CONFIG_DEV', q'[
        CREATE TABLE T_SYSTEM_CONFIG_DEV (
          CONFIG_KEY    VARCHAR2(100)   NOT NULL,
          CONFIG_VALUE  VARCHAR2(4000),
          VALUE_TYPE    VARCHAR2(16)    DEFAULT 'STRING' NOT NULL,
          DESCRIPTION   VARCHAR2(1000),
          UPDATED_BY    VARCHAR2(100),
          UPDATED_AT    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
          ROW_HASH      VARCHAR2(64),
          CONSTRAINT PK_T_SYSTEM_CONFIG_DEV PRIMARY KEY (CONFIG_KEY),
          CONSTRAINT CK_TSC_VALUE_TYPE CHECK (VALUE_TYPE IN ('STRING', 'BOOLEAN', 'NUMBER'))
        )]');
END;
